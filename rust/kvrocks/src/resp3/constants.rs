macro_rules! const_str {
    ($($name:ident $(= $val:expr)?),* $(,)?) => {
        $(
            pub const $name: &str = const_str!(@val $name $(= $val)?);
        )*
    };
    (@val $name:ident = $val:expr) => { $val };
    (@val $name:ident) => { stringify!($name) };
}

